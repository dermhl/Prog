from datetime import datetime # Импорт функции datetime из модуля datetime для работы с датой и временем
from math import sqrt # Импорт функции sqrt из модуля math для вычисления квадратного корня

def main(**kwargs): # Определение функции main, принимает произвольное количество аргументов
    # Перебираем все пары ключ-значение в словаре kwargs
    for key in kwargs.items():
        # Вычисляем длину гипотенузы по теореме Пифагора для каждого набора координат
        # key[1] — значение, то есть список из двух чисел
        # key[1][0] — первая координата
        # key[1][1] — вторая координата
        result = sqrt(key[1][0] ** 2 + key[1][1] ** 2)
        print(result)   # Выводим результат вычисления для текущего набора координат


if __name__ == '__main__':  # Проверяем, что скрипт запущен как основная программа
    start_time = datetime.now() # Запоминаем текущее время в переменную start_time для измерения времени выполнения

    # Вызываем функцию main с набором аргументов, каждый из которых — список из двух чисел
    main(
        one=[10, 3],  # Первый набор координат
        two=[5, 4],  # Второй набор координат
        three=[15, 13],  # Третий набор координат
        four=[93, 53],  # Четвертый набор координат
        five=[133, 15]  # Пятый набор координат
    )
    # Вычисляем разницу между текущим временем и начальным, чтобы определить время выполнения
    time_costs = datetime.now() - start_time
    print(f"Время выполнения программы - {time_costs}") # Выводим время выполнения программы в читаемом формате